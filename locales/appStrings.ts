export type AppLocale = "en" | "ru" | "zh";

export const APP_LOCALES: readonly AppLocale[] = ["en", "ru", "zh"] as const;

export const APP_LOCALE_DEFAULT: AppLocale = "en";

/** Fixed switcher labels (not localized — match AbraKadaVra-style EN / РУ / 中文). */
export const APP_LOCALE_SWITCHER_LABELS: Record<AppLocale, string> = {
  en: "EN",
  ru: "РУ",
  zh: "中文",
};

/** Cycle order for the header language icon and welcome switcher. */
export function nextAppLocale(locale: AppLocale): AppLocale {
  const index = APP_LOCALES.indexOf(locale);
  return APP_LOCALES[(index < 0 ? 0 : index + 1) % APP_LOCALES.length]!;
}

/** BCP-47 tag for `toLocaleString` / `Intl` formatting. */
export function appLocaleToBcp47(locale: AppLocale): string {
  if (locale === "ru") return "ru-RU";
  if (locale === "zh") return "zh-CN";
  return "en-US";
}
